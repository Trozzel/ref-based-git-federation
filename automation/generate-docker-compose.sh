#!/bin/bash
set -euo pipefail

NUM_SERVERS="${NUM_SERVERS:-3}"
LAB_DIR="${LAB_DIR:-/tmp/fed-lab}"
GITEA_BASE_PORT="${GITEA_BASE_PORT:-30000}"
GITEA_BASE_SSH_PORT="${GITEA_BASE_SSH_PORT:-2220}"
GITEA_IMAGE="${GITEA_IMAGE:-gitea/gitea:1.22.6}"
NATS_IMAGE="${NATS_IMAGE:-nats:2.11-alpine}"

cat <<EOF
services:
EOF

for i in $(seq 1 "${NUM_SERVERS}"); do
  http_port=$((GITEA_BASE_PORT + i))
  ssh_port=$((GITEA_BASE_SSH_PORT + i))

  cat <<EOF
  gitea-${i}:
    image: ${GITEA_IMAGE}
    container_name: gitea-${i}
    hostname: gitea-${i}
    environment:
      USER_UID: "1000"
      USER_GID: "1000"
      GITEA__security__INSTALL_LOCK: "true"
      GITEA__security__SECRET_KEY: "autogeneratedsecret"
      GITEA__database__DB_TYPE: "sqlite3"
      GITEA__database__PATH: "/data/gitea/gitea.db"
      GITEA__server__DOMAIN: "gitea-${i}"
      GITEA__server__SSH_DOMAIN: "gitea-${i}"
      GITEA__server__ROOT_URL: "http://localhost:${http_port}/"
      GITEA__server__HTTP_PORT: "3000"
      GITEA__server__SSH_PORT: "22"
      GITEA__webhook__ALLOWED_HOST_LIST: "host.docker.internal"
    restart: unless-stopped
    ports:
      - "${http_port}:3000"
      - "${ssh_port}:22"
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - "${LAB_DIR}/gitea-${i}:/data"
    networks:
      - fednet

EOF
done

cat <<EOF
  nats:
    image: ${NATS_IMAGE}
    container_name: fed-nats
    hostname: nats
    restart: unless-stopped
    ports:
      - "4222:4222"
      - "8222:8222"
    networks:
      - fednet

networks:
  fednet:
    driver: bridge
EOF
